def is_mobile_prefix_known(national: str) -> bool:
    """آیا پیشوند موبایل استاندارد است؟ (09 + 0/1/2/3/9)"""
    if not national.startswith("09") or len(national) != 11:
        return False
    return national[2] in VALID_MOBILE_SECOND_DIGITS


def is_synthetic_number(national: str) -> bool:
    """آیا شماره در بلوک مصنوعی اختصاص‌یافته به Fixtureهای تست قرار دارد؟

    الگو: ``0<کد استان>000...`` یا ``0912 000 ....`` — یعنی سه رقم اول مشترک، صفر است.
    چنین شماره‌ای در شماره‌گذاری واقعی ایران وجود ندارد.
    """
    digits = re.sub(r"\D", "", national or "").lstrip("0")
    if len(digits) < 9:
        return False
    return digits[-7:].startswith(SYNTHETIC_SUBSCRIBER_PREFIX)


def looks_like_national_id(digits: str) -> bool:
    if len(digits) != 10:
        return False
    if digits[0] == "0" and digits[3:9] == "000000":
        return True
    return digits.startswith("00") and digits[-2:] in {"00", "11"}


def normalize_area_code(value: str) -> str:
    """پیش‌شماره را به شکل ۰XX (۳ کاراکتر) درمی‌آورد."""
    digits = re.sub(r"\D", "", value or "")
    if not digits:
        return ""
    if digits.startswith("98") and len(digits) > 6:
        digits = digits[2:]
    if not digits.startswith("0"):
        digits = "0" + digits
    return digits
