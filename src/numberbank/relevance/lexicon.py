def load_reference_categories() -> dict[str, Any]:
    """بازنویسی/گسترش واژگان از فایل مرجع (بدون تغییر کد)."""
    path = Path(get_settings().data_dir) / "reference" / "categories.json"
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def _merge(base: list[tuple[str, float]], override) -> list[tuple[str, float]]:
    """منطق امن بازنویسی واژگان.

    فایل مرجع فقط **اضافه** می‌کند؛ برای جانشینی کامل باید ساختار
    ``{"replace": true, "terms": [[...]]}`` استفاده شود. مقدار خالی هیچ‌گاه
    واژگان پیش‌فرض را حذف نمی‌کند (جلوگیری از بی‌اثر شدن تشخیص ارتباط).
    """
    if isinstance(override, dict) and override.get("replace") and isinstance(override.get("terms"), list):
        return [(str(t), float(w)) for t, w in override["terms"]]
    if isinstance(override, list) and override:
        extra = [(str(t), float(w)) for t, w in override if isinstance(t, str)]
        seen = {t for t, _ in base}
        return base + [item for item in extra if item[0] not in seen]
    return base


def category_terms(code: str) -> list[tuple[str, float]]:
    data = load_reference_categories()
    return _merge(CATEGORY_TERMS.get(code, []), data.get("categories", {}).get(code))


def role_terms(code: str) -> list[tuple[str, float]]:
    data = load_reference_categories()
    return _merge(ROLE_TERMS.get(code, []), data.get("roles", {}).get(code))


def negative_terms() -> list[tuple[str, float]]:
    data = load_reference_categories()
    return _merge(NEGATIVE_TERMS, data.get("negative"))


def all_categories() -> list[str]:
    return [c.value for c in CategoryCode if c is not CategoryCode.OTHER]
